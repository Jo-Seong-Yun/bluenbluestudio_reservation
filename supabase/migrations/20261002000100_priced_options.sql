-- 객관식/체크박스 문항의 각 옵션에 가격을 매길 수 있게 한다(예: "추가옵션
-- (유료)"에서 "흑백영상 추가제공 (+10,000원)"). 지금까지는 그 금액이
-- 옵션 라벨 글자 안에 그냥 적혀 있어서(문자열일 뿐) 계산에 쓸 수
-- 없었다 — options와 같은 길이의 정수 배열을 나란히 둬서, i번째
-- 옵션의 가격은 option_prices[i]가 되게 한다. null이면(기존 문항 전부,
-- 또는 가격 없이 만든 새 문항) 그냥 예전처럼 가격 없는 옵션이다.
alter table custom_fields
  add column option_prices integer[];

-- 예약 신청 시점에 계산한 "예상 금액"(기본 상품가 + 체크한 유료 옵션
-- 합계) 스냅샷. 나중에 옵션 가격이 바뀌어도 이 예약 건의 신청 당시
-- 금액은 그대로 남아야 하므로 매번 다시 계산하지 않고 저장해 둔다.
-- 관리자가 매출관리에서 입력하는 "실제 지불액"(charged_amount)과는
-- 별개로, 신청 당시 참고용 숫자다.
alter table reservations
  add column estimated_amount integer;
