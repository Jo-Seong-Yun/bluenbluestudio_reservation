-- reservation-form.tsx에 하드코딩돼 있어 관리자가 손댈 수 없었다.
-- 이제 설정 화면에서 직접 고칠 수 있게 settings로 옮긴다. 비워두면
-- (null) 체크박스 자체가 사라지고 동의 없이 신청할 수 있다 —
-- 스튜디오가 굳이 이 문구를 안 쓰기로 할 수도 있어서다.
--
-- 기존 하드코딩 문구를 기본값으로 넣어, 배포 직후에도 지금과 똑같이
-- 보인다(관리자가 원할 때 설정에서 고치거나 비우면 된다).
